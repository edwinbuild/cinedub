import { expect, test } from "@playwright/test";

test("saved multilevel undo redo, keyboard navigation and conflicting drafts", async ({ page, context }) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  page.on("dialog", (dialog) => dialog.accept());
  await page.goto("/");
  await page.getByLabel("Project name").fill("Original saved edit review");
  await page.getByRole("button", { name: "Create workspace" }).click();
  await expect(page).toHaveURL(/\/projects\//);
  await page.getByRole("button", { name: /^Build demo timeline/ }).click();
  await expect(page.getByRole("heading", { name: "4 reviewable lines" })).toBeVisible();
  const line = (index: number) => page.getByRole("article", { name: `Dialogue line ${index}`, exact: true });
  const first = line(1), third = line(3);
  const english = first.getByLabel("English", { exact: true });
  const target = first.getByLabel("Malayalam", { exact: true });
  const originalEnglish = await english.inputValue();
  const originalTarget = await target.inputValue();
  await english.fill("An original manual English correction.");
  await english.press("Control+Enter");
  await expect(first.getByRole("button", { name: "Save line", exact: true })).toBeDisabled();
  await target.fill("മനുഷ്യൻ തിരുത്തിയ വരി");
  await target.press("Control+Enter");
  await expect(first.getByRole("button", { name: "Save line", exact: true })).toBeDisabled();
  let history = first.getByLabel("Saved history for line 1", { exact: true });
  await history.locator("summary").first().click();
  await expect(history.getByRole("button", { name: "Undo saved edit", exact: true })).toBeDisabled();
  await history.getByLabel("Restoring clears selected voice audio and requires approval again", { exact: true }).check();
  await history.getByRole("button", { name: "Undo saved edit", exact: true }).click();
  await expect(target).toHaveValue(originalTarget);
  await expect(english).toHaveValue("An original manual English correction.");
  await history.getByRole("button", { name: "Undo saved edit", exact: true }).click();
  await expect(english).toHaveValue(originalEnglish);
  await expect(first.getByLabel("Review state for line 1", { exact: true })).toHaveValue("needs_review");
  await page.reload();
  history = line(1).getByLabel("Saved history for line 1", { exact: true });
  await history.locator("summary").first().click();
  await history.getByLabel("Restoring clears selected voice audio and requires approval again", { exact: true }).check();
  await history.getByRole("button", { name: "Redo saved edit", exact: true }).click();
  await expect(english).toHaveValue("An original manual English correction.");
  await history.getByRole("button", { name: "Redo saved edit", exact: true }).click();
  await expect(target).toHaveValue("മനുഷ്യൻ തിരുത്തിയ വരി");
  await expect(history.getByRole("button", { name: "Redo saved edit", exact: true })).toBeDisabled();
  await english.fill("Preserve this local draft");
  await expect(history.getByRole("button", { name: "Undo saved edit", exact: true })).toBeDisabled();
  await english.press("Alt+ArrowDown");
  await expect(line(2)).toBeFocused();
  await line(2).press("Alt+ArrowUp");
  await expect(first).toBeFocused();
  await expect(english).toHaveValue("Preserve this local draft");
  const thirdEnglish = third.getByLabel("English", { exact: true });
  await thirdEnglish.fill("Third line edited for navigation.");
  await thirdEnglish.press("Control+Enter");
  await expect(third.getByRole("button", { name: "Save line", exact: true })).toBeDisabled();
  await page.getByRole("button", { name: "edited", exact: true }).click();
  await first.focus();
  await first.press("Alt+ArrowDown");
  await expect(third).toBeFocused();
  await expect(line(2)).toBeHidden();
  await page.getByRole("button", { name: "all", exact: true }).click();
  const other = await context.newPage();
  await other.goto(page.url());
  const remoteEnglish = other.getByRole("article", { name: "Dialogue line 1", exact: true }).getByLabel("English", { exact: true });
  await remoteEnglish.fill("Another editor's saved correction.");
  await remoteEnglish.press("Control+Enter");
  await expect(other.getByRole("article", { name: "Dialogue line 1", exact: true }).getByRole("button", { name: "Save line", exact: true })).toBeDisabled();
  await page.getByRole("button", { name: "Refresh project", exact: true }).click();
  await expect(english).toHaveValue("Preserve this local draft");
  await expect(first.getByText("This line changed on the server. Your draft is preserved.", { exact: false })).toBeVisible();
  await expect(first.getByRole("button", { name: "Save line", exact: true })).toBeDisabled();
  await expect(history.getByRole("button", { name: "Undo saved edit", exact: true })).toBeDisabled();
  await first.getByRole("button", { name: "Load saved line", exact: true }).click();
  await expect(english).toHaveValue("Another editor's saved correction.");
  await history.getByRole("button", { name: "Refresh saved history", exact: true }).click();
  await expect(history.getByRole("button", { name: "Undo saved edit", exact: true })).toBeEnabled();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await first.screenshot({ path: "test-results/cinedub-edit-history-mobile.png" });
  await other.close();
  expect(errors).toEqual([]);
});
